// Usage: node scripts/build-flags.mjs
import { readFileSync, writeFileSync, statSync, mkdirSync } from 'node:fs';
import sharp from 'sharp';

const [TW, TH] = [128, 96];
const years = JSON.parse(readFileSync('static/data/years.json', 'utf8')).years;
const codes = new Set();
for (const { year } of years) {
  for (const row of JSON.parse(readFileSync(`static/data/${year}/groups.json`, 'utf8')).groups) {
    if (row[3]) codes.add(String(row[3]).toUpperCase());
  }
}

const tiles = [];
const index = {};
for (const cc of [...codes].sort()) {
  const file = `static/flags/${cc.toLowerCase()}.svg`;
  let svg;
  try {
    svg = readFileSync(file);
  } catch {
    console.warn(`missing ${file}`);
    continue;
  }
  const tile = await sharp(svg, { density: 300 }).resize(TW, TH, { fit: 'fill' }).png().toBuffer();
  index[cc] = tiles.length;
  tiles.push(tile);
}

const n = tiles.length;
const cols = Math.ceil(Math.sqrt(n));
const rows = Math.ceil(n / cols);
mkdirSync('src/assets', { recursive: true });
await sharp({
  create: { width: cols * TW, height: rows * TH, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } },
})
  .composite(tiles.map((input, i) => ({ input, left: (i % cols) * TW, top: Math.floor(i / cols) * TH })))
  .webp({ quality: 88, effort: 6 })
  .toFile('src/assets/flags.webp');

writeFileSync('src/lib/flag-atlas.json', JSON.stringify({ tile: [TW, TH], cols, rows, index }, null, 2) + '\n');

const pct = (v, max) => (max > 0 ? +((v / max) * 100).toFixed(4) : 0);
let css = '/* Generated by scripts/build-flags.mjs from static/flags (flag-icons, MIT). */\n';
css += `.fi{background-image:url(./assets/flags.webp);background-size:${cols * 100}% ${rows * 100}%;background-repeat:no-repeat;position:relative;display:inline-block;width:1.333333em;line-height:1em}.fi:before{content:"\\00a0"}\n`;
for (const [cc, i] of Object.entries(index)) {
  css += `.fi-${cc.toLowerCase()}{background-position:${pct(i % cols, cols - 1)}% ${pct(Math.floor(i / cols), rows - 1)}%}\n`;
}
writeFileSync('src/flags.css', css);

const total = Object.keys(index).reduce((s, cc) => s + statSync(`static/flags/${cc.toLowerCase()}.svg`).size, 0);
console.log(`${n} flags, ${cols}x${rows} tiles, atlas ${statSync('src/assets/flags.webp').size} B, replaced svgs ${total} B`);
